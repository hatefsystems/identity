func waitForMigrationLock(ctx context.Context, t *testing.T, database *sql.DB) {
	t.Helper()
	bounded, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	ticker := time.NewTicker(10 * time.Millisecond)
	defer ticker.Stop()
	for {
		var locked bool
		if err := database.QueryRowContext(bounded, `SELECT EXISTS(SELECT 1 FROM pg_catalog.pg_locks WHERE locktype='advisory'
			AND objid=$1 AND granted AND database=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database()))`, pglock.MigrationKey).Scan(&locked); err != nil {
			t.Fatal(err)
		}
		if locked {
			return
		}
		select {
		case <-bounded.Done():
			t.Fatal("migration did not acquire exclusion")
		case <-ticker.C:
		}
	}
}

