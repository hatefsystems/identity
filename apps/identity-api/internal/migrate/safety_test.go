// Snapshot raw metadata rather than calling the guard on deliberately invalid
// fixtures. Sequence values catch accidental bookkeeping initialization too.
func metadataSnapshot(ctx context.Context, t *testing.T, database *sql.DB) string {
	t.Helper()
	var catalog string
	if err := database.QueryRowContext(ctx, `SELECT COALESCE(jsonb_agg(to_jsonb(c) ORDER BY c.oid)::text,'[]')
		FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
		WHERE n.nspname='public'`).Scan(&catalog); err != nil {
		t.Fatal(err)
	}
	for _, table := range []string{"goose_db_version", "identity_schema_version", "identity_schema_version_id_seq"} {
		var exists bool
		if err := database.QueryRowContext(ctx, `SELECT pg_catalog.to_regclass($1) IS NOT NULL`, "public."+table).Scan(&exists); err != nil {
			t.Fatal(err)
		}
		if exists {
			var rows string
			if err := database.QueryRowContext(ctx, `SELECT COALESCE(jsonb_agg(to_jsonb(h) ORDER BY to_jsonb(h)::text)::text,'[]') FROM (SELECT * FROM public.`+table+`) h`).Scan(&rows); err != nil {
				t.Fatal(err)
			}
			catalog += table + rows
		}
	}
	return catalog
}

func assertRejectedEntrypoints(ctx context.Context, t *testing.T, database *sql.DB, p *Provider) {
	t.Helper()
	before := metadataSnapshot(ctx, t, database)
	for name, run := range map[string]func() error{
		"Up":               func() error { _, err := p.Up(ctx); return err },
		"UpTo":             func() error { _, err := p.UpTo(ctx, 1); return err },
		"UpByOne":          func() error { _, err := p.UpByOne(ctx); return err },
		"ApplyVersionUp":   func() error { _, err := p.ApplyVersion(ctx, 1, true); return err },
		"ApplyVersionDown": func() error { _, err := p.ApplyVersion(ctx, 1, false); return err },
		"Down":             func() error { _, err := p.Down(ctx); return err },
		"DownToNoop":       func() error { _, err := p.DownTo(ctx, 1); return err },
		"DownToZero":       func() error { _, err := p.DownTo(ctx, 0); return err },
		"Reset":            func() error { return Reset(ctx, database) },
		"Status":           func() error { _, err := p.Status(ctx); return err },
		"GetDBVersion":     func() error { _, err := p.GetDBVersion(ctx); return err },
	} {
		t.Run(name, func(t *testing.T) {
			if err := run(); err == nil {
				t.Fatal("invalid lineage accepted")
			}
			if after := metadataSnapshot(ctx, t, database); before != after {
				t.Fatal("rejected call changed schema or metadata")
			}
		})
	}
}

