func TestCompetingFreshMigratorsSerialize(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), testTimeout)
	defer cancel()
	database := openTestDB(ctx, t)
	done := make(chan error, 3)
	for range 3 {
		go func() { done <- Up(ctx, database) }()
	}
	successes := 0
	for range 3 {
		err := <-done
		if err == nil {
			successes++
		} else if !strings.Contains(err.Error(), "exclusion") {
			t.Fatalf("competing first install: %v", err)
		}
	}
	if successes == 0 {
		t.Fatal("no competing migrator completed successfully")
	}
	var count int
	if err := database.QueryRowContext(ctx, `SELECT count(*) FROM public.identity_schema_version`).Scan(&count); err != nil || count != 2 {
		t.Fatalf("baseline not installed exactly once: %d, %v", count, err)
	}
	database.SetMaxOpenConns(1)
	if err := Up(ctx, database); err != nil {
		t.Fatalf("single pool forward retry: %v", err)
	}
}

func TestExclusionCancellationAndBadConnectionCleanup(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), testTimeout)
	defer cancel()
	database := openTestDB(ctx, t)
	for _, key := range migrationKeys {
		conn, err := database.Conn(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := conn.ExecContext(ctx, `SELECT pg_catalog.pg_advisory_lock($1)`, key); err != nil {
			t.Fatal(err)
		}
		bounded, stop := context.WithTimeout(ctx, 100*time.Millisecond)
		err = Up(bounded, database)
		stop()
		if err == nil || !errors.Is(err, context.DeadlineExceeded) {
			t.Fatalf("migration ignored held exclusion %d: %v", key, err)
		}
		if _, err := conn.ExecContext(ctx, `SELECT pg_catalog.pg_advisory_unlock($1)`, key); err != nil {
			t.Fatal(err)
		}
		_ = conn.Close()
	}
	var locks int
	if err := database.QueryRowContext(ctx, `SELECT count(*) FROM pg_catalog.pg_locks WHERE locktype='advisory'
		AND database=(SELECT oid FROM pg_catalog.pg_database WHERE datname=current_database())`).Scan(&locks); err != nil || locks != 0 {
		t.Fatalf("cancellation leaked locks: %d, %v", locks, err)
	}
	// An unlock error must evict the session, including locks still held by it.
	conn, err := database.Conn(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := conn.ExecContext(ctx, `SELECT pg_catalog.pg_advisory_lock($1)`, migrationKeys[0]); err != nil {
		t.Fatal(err)
	}
	if err := unlockMigration(conn, 2); err == nil {
		t.Fatal("unobserved lock release did not discard connection")
	}
	_ = conn.Close()
	database.SetMaxOpenConns(1)
	if err := Up(ctx, database); err != nil {
		t.Fatalf("retry after bad session cleanup: %v", err)
	}
}

func TestBaselineFinalSecurityAndPhantomTerminal(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), testTimeout)
	defer cancel()
	database := openTestDB(ctx, t)
	database.SetMaxOpenConns(1)
	if err := Up(ctx, database); err != nil {
		t.Fatal(err)
	}
	var definer, publicExecute bool
	var config string
	if err := database.QueryRowContext(ctx, `SELECT p.prosecdef,p.proconfig::text,
		EXISTS(SELECT 1 FROM pg_catalog.aclexplode(COALESCE(p.proacl,pg_catalog.acldefault('f',p.proowner))) a WHERE a.grantee=0 AND a.privilege_type='EXECUTE')
		FROM pg_catalog.pg_proc p WHERE p.oid='public.advance_chain_head(text,bigint,bigint,bigint,bigint)'::regprocedure`).Scan(&definer, &config, &publicExecute); err != nil {
		t.Fatal(err)
	}
	if !definer || publicExecute || !strings.Contains(config, "search_path=pg_catalog, pg_temp") || !strings.Contains(config, "lock_timeout=2s") {
		t.Fatalf("head function security drift: %v, %v, %s", definer, publicExecute, config)
	}
	for _, chain := range []struct{ name, head, nodes, genesis, prefix string }{
		{"audit", "audit_log_head", "audit_log_chain", audit.GoldenAuditGenesisHex, "hatef.audit.chain.v2"},
		{"ledger", "security_ledger_head", "security_ledger_chain", audit.GoldenLedgerGenesisHex, "hatef.ledger.chain.v2"},
	} {
		execFixture(ctx, t, database, `INSERT INTO public.`+chain.head+`(singleton,seq,chain_hash) VALUES(true,0,decode($1,'hex'))`, chain.genesis)
		execFixture(ctx, t, database, `INSERT INTO public.`+chain.nodes+`(seq,event_id,leaf_hash,chain_hash) VALUES(3,gen_random_uuid(),sha256('leaf'),
			sha256(convert_to($1,'UTF8') || '\x00'::bytea || decode($2,'hex') || sha256('leaf')))`, chain.prefix, chain.genesis)
		if _, err := database.ExecContext(ctx, `SELECT public.advance_chain_head($1,0,3,4,1)`, chain.name); err == nil || !strings.Contains(err.Error(), "terminal") {
			t.Fatalf("%s phantom terminal accepted: %v", chain.name, err)
		}
		var seq int64
		if err := database.QueryRowContext(ctx, `SELECT seq FROM public.`+chain.head).Scan(&seq); err != nil || seq != 0 {
			t.Fatalf("failed advancement changed %s head: %d, %v", chain.name, seq, err)
		}
		execFixture(ctx, t, database, `SELECT public.advance_chain_head($1,0,3,3,1)`, chain.name)
		for _, query := range []string{`UPDATE public.` + chain.nodes + ` SET chain_hash=sha256('tampered')`, `DELETE FROM public.` + chain.nodes, `TRUNCATE public.` + chain.nodes} {
			if _, err := database.ExecContext(ctx, query); err == nil {
				t.Fatalf("chain mutation accepted: %s", query)
			}
		}
	}
	before := metadataSnapshot(ctx, t, database)
	if err := Down(ctx, database); err == nil || !strings.Contains(err.Error(), "forward-only") {
		t.Fatalf("baseline down: %v", err)
	}
	if before != metadataSnapshot(ctx, t, database) {
		t.Fatal("baseline down changed metadata")
	}
	if err := Up(ctx, database); err != nil {
		t.Fatal(err)
	}
}
